'use client';

import {
  AdminCard,
  AdminBadge,
  AdminDateCell,
  AdminAccordion,
} from '../../../shared/components/Misc';
import type { AdminStudentPracticeReport } from '../../../core/api/admin-student-practice-report-api';

type Props = {
  readonly report: AdminStudentPracticeReport;
};

const TREND_VARIANT: Record<string, 'success' | 'warning' | 'neutral'> = {
  improving: 'success',
  declining: 'warning',
  stable: 'neutral',
};

function Stat({ label, value }: { readonly label: string; readonly value: string | number }) {
  return (
    <div className="flex flex-col gap-1 min-w-[96px]">
      <span className="text-xs text-[var(--text-muted)]">{label}</span>
      <span className="text-xl font-semibold text-[var(--text-primary)]">{value}</span>
    </div>
  );
}

export function StudentPracticeReportClient({ report }: Props) {
  const { totals, sessions, skills, focusDirectives } = report;

  return (
    <div className="flex flex-col gap-4">
      <AdminCard>
        <h2 className="text-base font-semibold text-[var(--text-primary)] mb-3">Practice results</h2>
        <div className="flex flex-wrap gap-6">
          <Stat label="Practice sessions" value={totals.sessions} />
          <Stat label="Answers" value={totals.attempts} />
          <Stat label="Correct" value={totals.correct} />
          <Stat label="Wrong" value={totals.wrong} />
          <Stat label="Accuracy" value={`${totals.accuracyPercent}%`} />
        </div>
      </AdminCard>

      <AdminAccordion
        title="Mastery by skill"
        summary={<span className="text-xs text-[var(--text-muted)]">{skills.length}</span>}
      >
        {skills.length === 0 ? (
          <p className="text-sm text-[var(--text-muted)] pt-4">No skills have been scored yet.</p>
        ) : (
          <div className="flex flex-col gap-2 pt-4">
            {skills.map((s) => (
              <div
                key={s.skillKey}
                className="flex flex-wrap items-center gap-3 py-2 border-b border-[var(--border)] last:border-b-0"
              >
                <span className="text-sm text-[var(--text-primary)] flex-1 min-w-[160px]">
                  {s.title ?? s.skillKey}
                </span>
                <span className="text-sm font-medium text-[var(--text-primary)]">
                  {s.masteryPercent === null ? '—' : `${s.masteryPercent}%`}
                  {s.previousMasteryPercent !== null && s.masteryPercent !== null && (
                    <span className="text-xs text-[var(--text-muted)]"> (was {s.previousMasteryPercent}%)</span>
                  )}
                </span>
                {s.trend && <AdminBadge variant={TREND_VARIANT[s.trend] ?? 'neutral'}>{s.trend.replace('_', ' ')}</AdminBadge>}
                <span className="text-xs text-[var(--text-muted)]">
                  {s.correct} correct · {s.wrong} wrong
                </span>
              </div>
            ))}
          </div>
        )}
      </AdminAccordion>

      <AdminAccordion
        title="Practice sessions"
        summary={<span className="text-xs text-[var(--text-muted)]">{sessions.length}</span>}
      >
        {sessions.length === 0 ? (
          <p className="text-sm text-[var(--text-muted)] pt-4">No practice answers yet.</p>
        ) : (
          <div className="flex flex-col gap-2 pt-4">
            {sessions.map((s) => (
              <div
                key={s.sessionId}
                className="flex flex-wrap items-center gap-3 py-2 border-b border-[var(--border)] last:border-b-0"
              >
                <span className="text-sm text-[var(--text-primary)] flex-1 min-w-[160px]">
                  {s.skillFocus.length > 0 ? s.skillFocus.join(', ') : s.sessionType}
                </span>
                <span className="text-xs text-[var(--text-muted)]">
                  {s.correct} correct · {s.wrong} wrong of {s.attempts}
                </span>
                <span className="text-xs text-[var(--text-muted)]">
                  <AdminDateCell iso={s.startedAt} />
                </span>
              </div>
            ))}
          </div>
        )}
      </AdminAccordion>

      <AdminAccordion
        title="Prompt generated by the engine"
        summary={<span className="text-xs text-[var(--text-muted)]">{focusDirectives.length}</span>}
      >
        {focusDirectives.length === 0 ? (
          <p className="text-sm text-[var(--text-muted)] pt-4">The engine has not generated a prompt for this student yet.</p>
        ) : (
          <div className="flex flex-col gap-3 pt-4">
            {focusDirectives.map((d) => (
              <div key={`${d.skillKey}-${d.generatedAt}`} className="flex flex-col gap-1 py-2 border-b border-[var(--border)] last:border-b-0">
                <div className="flex flex-wrap items-center gap-2">
                  <AdminBadge variant={d.active ? 'success' : 'neutral'}>{d.active ? 'active' : 'past'}</AdminBadge>
                  <span className="text-xs text-[var(--text-muted)]">{d.skillKey} · {d.source.replace('_', ' ')}</span>
                  <span className="text-xs text-[var(--text-muted)]"><AdminDateCell iso={d.generatedAt} /></span>
                </div>
                <p className="text-sm text-[var(--text-primary)] whitespace-pre-wrap">{d.text}</p>
              </div>
            ))}
          </div>
        )}
      </AdminAccordion>
    </div>
  );
}
