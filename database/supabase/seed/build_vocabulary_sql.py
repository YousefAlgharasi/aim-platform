#!/usr/bin/env python3
"""Build seed_11_vocabulary_words.sql from vocabulary_words.txt (idempotent: existing words are kept)."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
LEVELS = {'beginner', 'intermediate', 'advanced'}
POS = {'noun', 'verb', 'adjective', 'adverb', 'preposition', 'conjunction', 'pronoun', 'phrase'}
q = lambda s: "'" + s.replace("'", "''") + "'"
rows, seen, errors = [], set(), []
for n, line in enumerate(open(os.path.join(HERE, 'vocabulary_words.txt'), encoding='utf-8'), 1):
    line = line.strip()
    if not line or line.startswith('#'):
        continue
    p = line.split('|')
    if len(p) != 5: errors.append(f'line {n}: expected 5 fields'); continue
    lvl, word, pos, ar, ex = [x.strip() for x in p]
    if lvl not in LEVELS: errors.append(f'line {n}: bad level {lvl}')
    if pos not in POS: errors.append(f'line {n}: bad part of speech {pos}')
    if word.lower() in seen: errors.append(f'line {n}: duplicate word {word}')
    if word.lower() not in ex.lower() and not (word.lower()[:-1] in ex.lower()): errors.append(f'line {n}: example does not use "{word}"')
    seen.add(word.lower())
    rows.append((lvl, word, pos, ar, ex))
if errors:
    print('\n'.join(errors)); sys.exit(1)
out = ['-- GENERATED by build_vocabulary_sql.py from vocabulary_words.txt — do not edit by hand.',
       '-- Needs migration 20261109120000_create_vocabulary_words. Existing words are left untouched.', 'BEGIN;']
for i, (lvl, word, pos, ar, ex) in enumerate(rows):
    out.append(f"INSERT INTO vocabulary_words (word, translation_ar, example_sentence, part_of_speech, level, sort_order) "
               f"VALUES ({q(word)}, {q(ar)}, {q(ex)}, {q(pos)}, {q(lvl)}, {i}) ON CONFLICT DO NOTHING;")
out.append('COMMIT;')
dest = os.path.join(HERE, 'seed_11_vocabulary_words.sql')
open(dest, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
from collections import Counter
print(len(rows), 'words', dict(Counter(r[0] for r in rows)))
